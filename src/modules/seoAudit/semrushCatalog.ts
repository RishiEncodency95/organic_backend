export function plainFor(id: number, name: string, fix: string): { plain: string; why: string } {
  const entry = PLAIN[id] ?? PLAIN_MORE[id];
  return entry ? { plain: entry[0], why: entry[1] } : { plain: `The report found: ${name}.`, why: fix };
}
