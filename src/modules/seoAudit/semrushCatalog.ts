/**
 * Who fixes each Semrush check, and what to do about it.
 *
 * Keyed by Semrush's own Issue Id (the first column of the issues file), so a check is recognised even if Semrush
 * rewords its name. Anything missing here (a check Semrush adds later) still shows up, with a generic instruction.
 *
 *   developer  needs a code, template, server or DNS change
 *   seo        a content / metadata / linking decision the SEO owner can make from the admin
 *
 * `templateWhenSitewide`: these are normally per-page content edits, but when the same problem is on most pages it
 * lives in the shared header, footer or layout, so it becomes a developer task instead of dozens of page edits.
 */

export type TaskOwner = "developer" | "seo";

export interface CatalogEntry {
  owner: TaskOwner;
  fix: string;
  templateWhenSitewide?: boolean;
}

